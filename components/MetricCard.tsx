export default function MetricCard({ item }: MetricCardCorps) {
    const trendColor = item.trend === "up"
        ? "text-emerald-400"
        : item.trend === "down"
            ? "text-red-400"
            : "text-slate-300";

    return (
        <div className="rounded-2xl border border-slate-800 bg-slate-900 p-6 shadow-sm hover:border-slate-700 transition-colors">
            <div className="flex items-start justify-between">
                <div className="w-12 h-12 rounded-full bg-teal-500/20 text-teal-400 flex items-center justify-center flex-shrink-0">
                    {getIcon(item.title)}
                </div>
                {item.change ? (
                    <span className={`text-xs font-medium ${trendColor}`}>{item.change}</span>
                ) : null}
            </div>
            <p className="mt-4 text-sm text-slate-400">{item.title}</p>
            <div className="mt-2">
                <h3 className="text-md lg:text-lg font-bold text-white">{item.value}</h3>
            </div>
        </div>
    )
}